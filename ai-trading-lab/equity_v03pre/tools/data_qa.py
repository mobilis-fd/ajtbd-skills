"""Data QA for Equity Alpha Screening v0.3-pre inputs (no network, no strategy returns).

Usage: python -I data_qa.py DATA_DIR OUT_MD
DATA_DIR = ai-trading-lab/data/equity_v03pre (contains raw/, inputs/, nasdaq_* files).
Writes a markdown QA report. Does not compute any event, control or strategy statistic.
"""
import json, sys, hashlib
from pathlib import Path
import numpy as np
import pandas as pd
import exchange_calendars as xcals
import pandas_market_calendars as pmc

SYMS = ['SPY', 'IEF', 'TLT']
UNSCHEDULED = ['2004-06-11', '2007-01-02', '2012-10-29', '2012-10-30', '2018-12-05', '2025-01-09']


def main(d, out_md):
    d = Path(d); L = []
    p = L.append
    p('# Data QA — Equity Alpha Screening v0.3-pre\n')
    p('Generated by `equity_v03pre/tools/data_qa.py`. No event or strategy statistic is computed here.\n')
    # --- provenance
    p('## 1. Provenance and hashes\n')
    p('| file | sha256 | bytes |'); p('|---|---|---|')
    for f in sorted((d / 'raw').iterdir()):
        p(f'| raw/{f.name} | `{hashlib.sha256(f.read_bytes()).hexdigest()}` | {f.stat().st_size} |')
    for f in sorted((d / 'inputs').glob('*.csv')):
        if f.name in ('sessions.csv',) or f.stem in SYMS:
            p(f'| inputs/{f.name} | `{hashlib.sha256(f.read_bytes()).hexdigest()}` | {f.stat().st_size} |')
    for s in SYMS:
        meta = json.loads((d / 'raw' / f'yahoo_{s}.json').read_text())['chart']['result'][0]['meta']
        ts = (d / 'raw' / f'yahoo_{s}.download_ts').read_text().strip()
        p(f'\n- {s}: Yahoo v8 chart API, downloaded {ts}, exchange {meta.get("fullExchangeName")}, '
          f'type {meta.get("instrumentType")}, tz {meta.get("exchangeTimezoneName")}')
    # --- calendar
    p('\n## 2. Trading calendar\n')
    cal = pd.read_csv(d / 'inputs' / 'sessions.csv', parse_dates=['date']).date
    cal = pd.DatetimeIndex(cal)
    nyse = pmc.get_calendar('NYSE').schedule(start_date='2002-12-01', end_date=cal[-1].strftime('%Y-%m-%d'))
    pm = pd.DatetimeIndex(nyse.index)
    p(f'- sessions.csv (exchange_calendars {xcals.__version__}, XNYS): {len(cal)} sessions {cal[0].date()} … {cal[-1].date()}')
    p(f'- pandas_market_calendars {pmc.__version__} NYSE over same range: {len(pm)} sessions; '
      f'only in XNYS: {[str(x.date()) for x in cal.difference(pm)]}; only in PMC: {[str(x.date()) for x in pm.difference(cal)]}')
    for s in SYMS:
        y = pd.read_csv(d / 'inputs' / f'{s}_raw_parsed.csv', parse_dates=['date']).date
        y = pd.DatetimeIndex(y)
        p(f'- Yahoo {s} dates vs calendar: missing {[str(x.date()) for x in cal.difference(y)]}, extra {[str(x.date()) for x in y.difference(cal)]}')
    p(f'- Unscheduled closures inside the range (not sessions in calendar, confirmed absent): '
      + ', '.join(f'{u} ({"absent" if pd.Timestamp(u) not in cal else "PRESENT"})' for u in UNSCHEDULED))
    xc = xcals.get_calendar('XNYS', start='2002-12-01', end=cal[-1].strftime('%Y-%m-%d'))
    early = [t for t in xc.early_closes if pd.Timestamp('2002-12-01') <= t <= cal[-1]]
    p(f'- Early closes (13:00) in range: {len(early)} (kept as normal sessions, as README requires)')
    m = cal.to_period('M'); cnt = pd.Series(1, index=m).groupby(level=0).sum()
    p(f'- Sessions per month: min {cnt.min()} ({", ".join(str(x) for x in cnt[cnt == cnt.min()].index)}), max {cnt.max()}; '
      f'last month in file {cnt.index[-1]} has {cnt.iloc[-1]} sessions (partial; the script skips months with <15 sessions)')
    # months whose last-5 / first-3 session set differs between scheduled and realised calendar
    p('- Months where an unscheduled closure changes which sessions are "last five" / "first three": '
      'see AUDIT.md A4 (2012-10: Oct 29–30 closed; 2007-01: Jan 2 closed). Others fall mid-month.')
    # --- prices
    p('\n## 3. Price integrity (Yahoo raw, split-adjusted OHLC)\n')
    p('| symbol | rows | NaN | non-positive | open/close outside [low, high] | zero volume | max abs close-to-close | max abs overnight gap | open==prev close | open==close (high>low) |')
    p('|---|---|---|---|---|---|---|---|---|---|')
    raw = {}
    for s in SYMS:
        x = pd.read_csv(d / 'inputs' / f'{s}_raw_parsed.csv', parse_dates=['date']).set_index('date'); raw[s] = x
        cc = x.close.pct_change().abs(); gap = (x.open / x.close.shift() - 1).abs()
        bad_hl = ((x[['open', 'close']].max(axis=1) > x.high * 1.0001) | (x[['open', 'close']].min(axis=1) < x.low * 0.9999)).sum()
        f1 = (x.open.round(4) == x.close.shift().round(4)).sum(); f2 = ((x.open.round(4) == x.close.round(4)) & (x.high > x.low)).sum()
        p(f'| {s} | {len(x)} | {int(x.isna().sum().sum())} | {int((x[["open","high","low","close","adjclose"]] <= 0).sum().sum())} | {int(bad_hl)} | {int((x.volume == 0).sum())} | '
          f'{cc.max():.4f} ({cc.idxmax().date()}) | {gap.max():.4f} ({gap.idxmax().date()}) | {int(f1)} | {int(f2)} |')
    p('\nThe last two columns are heuristics for stale opens; for IEF with a 1-cent tick they are often legitimate. '
      'They are not errors by themselves; see section 5 for the verified discrepancies.')
    # --- corporate actions
    p('\n## 4. Corporate actions\n')
    for s in SYMS:
        sp = pd.read_csv(d / 'inputs' / f'{s}_splits.csv') if (d / 'inputs' / f'{s}_splits.csv').stat().st_size > 1 else pd.DataFrame()
        x = raw[s]; big = x.close.pct_change().abs()
        p(f'- {s}: splits reported by Yahoo: {len(sp)}; days with |close-to-close| > 15%: {int((big > .15).sum())}')
    p('- None of SPY, IEF, TLT had a split in the period per Yahoo; no unexplained price discontinuity (>15%) was found.')
    p('\n### Dividend adjustment consistency (Yahoo adjclose vs Yahoo dividend events)\n')
    p('Daily factor implied by Yahoo: k_t = (adjclose_{t-1}/close_{t-1}) / (adjclose_t/close_t). '
      'Expected: k_t = 1 − D_t/close_{t-1} on ex-dates, 1 otherwise.\n')
    p('| symbol | dividends | ex-dates matched | max abs error on ex-dates | non-ex days with |k−1|>1e-5 | dividends on non-sessions |')
    p('|---|---|---|---|---|---|')
    for s in SYMS:
        x = raw[s]; dv = pd.read_csv(d / 'inputs' / f'{s}_dividends.csv', parse_dates=['date'])
        dv = dv.groupby('date').amount.sum()
        r = x.adjclose / x.close; k = r.shift() / r
        exp = pd.Series(1.0, index=x.index)
        on = dv.index.intersection(x.index); off = dv.index.difference(x.index)
        exp.loc[on] = 1 - dv.loc[on].values / x.close.shift().loc[on].values
        err = (k - exp).abs().iloc[1:]
        nonex = err.drop(on, errors='ignore')
        p(f'| {s} | {len(dv)} | {len(on)} | {err.reindex(on).max():.2e} (first-row ex-dates unverifiable: {int(err.reindex(on).isna().sum())}) | {int((nonex > 1e-5).sum())} | {[str(t.date()) for t in off]} |')
        bad = nonex[nonex > 1e-5]
        if len(bad):
            p(f'\n  {s} unexplained factor changes: ' + ', '.join(f'{t.date()} ({v:.2e})' for t, v in bad.head(20).items()) + '\n')
    # cross-source dividends
    p('\n### Dividends vs second source (Nasdaq dividend-history API, read 2026-11-27 via browser)\n')
    nq = {}
    for line in (d / 'nasdaq_dividends.txt').read_text().split('\n'):
        if not line.strip(): continue
        s, body = line.split(' ', 1)
        nq[s] = pd.Series({pd.Timestamp(a): float(b) for a, b in (z.split(':') for z in body.split(';'))})
    p('Nasdaq has no SPY dividend history via this endpoint; SPY dividends are checked only by internal consistency above.\n')
    p('| symbol | Yahoo events | Nasdaq events | common dates | amount mismatches (>0.0006, Yahoo rounds to 3 dp) | Yahoo-only dates | Nasdaq-only dates |')
    p('|---|---|---|---|---|---|---|')
    for s in ['IEF', 'TLT']:
        y = pd.read_csv(d / 'inputs' / f'{s}_dividends.csv', parse_dates=['date']).groupby('date').amount.sum()
        y = y[y.index <= pd.Timestamp('2026-11-06')]; n = nq[s][nq[s].index <= pd.Timestamp('2026-11-06')].sort_index()
        c = y.index.intersection(n.index); mm = c[(y.loc[c] - n.loc[c]).abs() > 0.0006]
        yo = y.index.difference(n.index); no = n.index.difference(y.index)
        p(f'| {s} | {len(y)} | {len(n)} | {len(c)} | {len(mm)} {[str(t.date()) for t in mm][:8]} | {len(yo)} | {len(no)} {[str(t.date()) for t in no][:8]} |')
    p('\nNasdaq history has gaps (2007-08 … 2011-03 and scattered months); Yahoo-only dates are therefore expected and are not by themselves errors.')
    # --- ex-date location relevant to EQ03 / EQ01
    p('\n### Ex-dividend location within the month (relevant to EQ01/EQ03 windows)\n')
    for s in SYMS:
        dv = pd.read_csv(d / 'inputs' / f'{s}_dividends.csv', parse_dates=['date']).date
        pos = []
        for t in dv:
            if t not in cal: continue
            mm_ = cal[cal.to_period('M') == t.to_period('M')]
            i = mm_.get_loc(t); pos.append((i, len(mm_) - 1 - i))
        first = sum(1 for a, b in pos if a == 0); last5 = sum(1 for a, b in pos if b <= 4)
        p(f'- {s}: {len(pos)} ex-dates on sessions; on first session of month: {first}; within last five sessions: {last5}')
    # --- second source prices
    p('\n## 5. Prices vs second source (Nasdaq historical API, 2016-11-25 … 2026-11-06 only)\n')
    p('Stooq (the README-suggested alternative) refused automated downloads from both the cloud host (connection reset) and a browser ("Access denied"); '
      'not bypassed. Nasdaq provides only the last 10 years, so T3 (2003–2016) has no second price source.\n')
    p('Method: per calendar month, compare session count, sum of day numbers, sum of open and close in cents. '
      'Months with any difference were then compared day by day (`nasdaq_days_mismatch_months.csv`).\n')
    nqs = json.loads((d / 'nasdaq_monthsums.json').read_text())
    for s in SYMS:
        a = {k: list(map(int, v.split(','))) for k, v in (z.split(':') for z in nqs[s].split(';'))}
        b = {k: list(map(int, v.split(','))) for k, v in (z.split(':') for z in (d / f'yahoo_monthsums_{s}.txt').read_text().split(';'))}
        p(f'- {s}: {len(a)} months, date-set mismatches {sum(a[k][:2] != b[k][:2] for k in a)}, '
          f'months with open differences {sum(a[k][2] != b[k][2] for k in a)}, with close differences {sum(a[k][3] != b[k][3] for k in a)}')
    disc = pd.read_csv(d / 'open_close_discrepancies_nasdaq_vs_yahoo.csv')
    p('\nDay-level discrepancies (> 0.6 cent):\n')
    p(disc.to_markdown(index=False))
    p('\nInterpretation: on most listed days Yahoo\'s open equals the previous close or the same-day close while Nasdaq has a distinct opening price, '
      'i.e. a stale Yahoo open. 2026-04-20 SPY is the reverse (Nasdaq row repeats the prior close; Yahoo is plausible). '
      'Close discrepancies are ≤ 9 cents on 4 days. The Yahoo open is the entry price of every event and control window, so this is a material QA item; '
      'it is handled by the pre-registered sensitivity S1 (PROTOCOL.md), not by editing the primary input.')
    Path(out_md).write_text('\n'.join(L) + '\n', encoding='utf8')
    print('wrote', out_md)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
